const arcsBetween = (_, labels, pos = 'top', gap = 1) => labels.map((lab, i) => {
  const f = gap === 2 ? (pos === 'top' ? i * 2 : i * 2 + 1) : i;
  return { f, t: f + gap, lab, pos, expr: '' };
});

